#!/usr/bin/env node
/* Builds the Svelte package's stylesheet from the React package's extracted CSS.
 *
 * Derived, not hand-copied: for every ported .svelte component it takes the
 * matching dist/css/components/<file>.css verbatim, between sentinels, then
 * appends svelte-only.css. Both packages therefore ship byte-identical rules for
 * every shared component, and porting a component brings its CSS automatically.
 *
 *   node scripts/build-svelte-css.js           write
 *   node scripts/build-svelte-css.js --check   exit 1 if the committed file is stale
 *
 * Requires `npm run build` first (it reads dist/). */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { resolve, relative } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const META = resolve(ROOT, 'dist/component-meta.json')
const CSS_DIR = resolve(ROOT, 'dist/css/components')
const SVELTE = resolve(ROOT, 'packages/svelte/src')
const OUT = resolve(SVELTE, 'styles/ui-kit-svelte.css')
const THEME_SRC = resolve(ROOT, 'dist/css/theme.css')
const THEME_OUT = resolve(SVELTE, 'styles/theme.css')

if (!existsSync(META) || !existsSync(CSS_DIR)) {
  console.error('[svelte-css] FAIL: dist/ is missing — run `npm run build` first.')
  process.exit(1)
}

const meta = JSON.parse(readFileSync(META, 'utf8'))
const fileByName = Object.fromEntries(meta.components.map(c => [c.name, c.fileName]))

const ported = readdirSync(resolve(SVELTE, 'components'))
  .filter(f => f.endsWith('.svelte'))
  .map(f => f.replace(/\.svelte$/, ''))
  .sort()

// Denominator check: nothing ported means nothing to build, not a pass.
if (ported.length === 0) {
  console.error('[svelte-css] FAIL: no .svelte components found.')
  process.exit(1)
}

const parts = [
  '/* GENERATED by scripts/build-svelte-css.js — do not edit.',
  ' * Component rules are copied verbatim from @frontier-labs/ui-kit\'s extracted CSS. */',
  '',
]
let failed = false
for (const name of ported) {
  const file = fileByName[name]
  const css = file && resolve(CSS_DIR, `${file}.css`)
  if (!css || !existsSync(css)) {
    console.error(`[svelte-css] FAIL: ${name} has no extracted CSS (looked for ${file}.css)`)
    failed = true
    continue
  }
  parts.push(`/* ${file} */`, readFileSync(css, 'utf8').trim(), `/* end ${file} */`, '')
}
if (failed) process.exit(1)
parts.push('/* svelte-only */', readFileSync(resolve(SVELTE, 'styles/svelte-only.css'), 'utf8').trim(), '/* end svelte-only */', '')

const next = parts.join('\n')
const theme = readFileSync(THEME_SRC, 'utf8')

if (process.argv.includes('--check')) {
  const stale = [[OUT, next], [THEME_OUT, theme]].filter(([p, body]) => !existsSync(p) || readFileSync(p, 'utf8') !== body)
  for (const [p] of stale) console.error(`[svelte-css] STALE: ${relative(ROOT, p)} — run \`npm run build:svelte-css\``)
  if (stale.length) process.exit(1)
  console.log(`[svelte-css] fresh: ${ported.length} component(s)`)
} else {
  writeFileSync(OUT, next)
  writeFileSync(THEME_OUT, theme)
  console.log(`[svelte-css] ${ported.length} component(s), ${next.length} bytes -> ${relative(ROOT, OUT)}`)
}
