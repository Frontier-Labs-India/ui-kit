#!/usr/bin/env node
/* Extracts React's unitless-number style properties from the installed
 * react-dom, into the Svelte package.
 *
 * React appends "px" to a numeric style value unless the value is 0 or the
 * property is in this set, so `style={{ width: 50 }}` means 50px and
 * `style={{ opacity: 0.5 }}` means 0.5. Porting a component's style object to
 * Svelte needs the same list, and a hand-copied one would drift on the next
 * React upgrade. Read from the source that actually does the rendering.
 *
 *   node scripts/extract-react-unitless.js           write
 *   node scripts/extract-react-unitless.js --check   exit 1 if stale */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, relative } from 'node:path'
import { createRequire } from 'node:module'

const ROOT = resolve(import.meta.dirname, '..')
const require = createRequire(import.meta.url)
const version = require('react-dom/package.json').version
const SRC = resolve(ROOT, 'node_modules/react-dom/cjs/react-dom-server.node.development.js')
const OUT = resolve(ROOT, 'packages/svelte/src/lib/unitless.generated.ts')

const text = readFileSync(SRC, 'utf8')
const m = text.match(/unitlessNumbers = new Set\(\s*"([^"]+)"\.split\(\s*" "\s*\)/)
if (!m) {
  console.error(`[unitless] FAIL: could not find unitlessNumbers in ${relative(ROOT, SRC)} — react-dom ${version} changed shape`)
  process.exit(1)
}
const names = m[1].trim().split(/\s+/)
// Denominator: React has carried ~50 of these for years; a tiny list means a bad parse.
if (names.length < 40 || !names.includes('opacity') || !names.includes('zIndex')) {
  console.error(`[unitless] FAIL: parsed ${names.length} names, expected opacity and zIndex among 40+`)
  process.exit(1)
}

const next = `/* GENERATED by scripts/extract-react-unitless.js from react-dom ${version} — do not edit.
 * Style properties React leaves unitless when given a number. */

export const UNITLESS = new Set<string>(${JSON.stringify(names, null, 2)})
`

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== next) {
    console.error(`[unitless] STALE: ${relative(ROOT, OUT)} — run \`npm run build:unitless\``)
    process.exit(1)
  }
  console.log(`[unitless] fresh: ${names.length} properties (react-dom ${version})`)
} else {
  writeFileSync(OUT, next)
  console.log(`[unitless] ${names.length} properties from react-dom ${version} -> ${relative(ROOT, OUT)}`)
}
